<?php

declare(strict_types=1);

namespace App\Classes\Publishers;

use App\Data\PostData;
use App\Data\PublishVideoData;
use App\Enums\ChannelType;
use App\Models\Channel;
use App\Models\Prompt;
use App\Tasks\Channels\IsChannelProjectActive;
use App\Tasks\Posts\SavePost;
use Illuminate\Support\Carbon;
use Illuminate\Support\Facades\URL;
use RuntimeException;
use Spatie\MediaLibrary\MediaCollections\Models\Media;

/**
 * Общий контекст канала и готового Prompt, доступ к медиа и запись Post.
 * Адаптер вызывает savePost после подтверждения публикации внешним сервисом.
 */
abstract class AbstractPublisher implements Publisher
{
    public function __construct(
        protected readonly Channel $channel,
        protected readonly Prompt|PublishVideoData $prompt,
        private readonly SavePost $savePost,
        private readonly IsChannelProjectActive $projectActive,
    ) {}

    public function channel(): Channel
    {
        return $this->channel;
    }

    public function source(): Prompt|PublishVideoData
    {
        return $this->prompt;
    }

    protected function getPath(): ?string
    {
        return $this->prompt instanceof PublishVideoData ? $this->prompt->path : $this->prompt->getFirstMedia()?->getPath();
    }

    protected function getVideoUrl(): string
    {
        if ($this->prompt instanceof PublishVideoData) {
            return $this->prompt->url;
        }

        $media = $this->prompt->getFirstMedia();

        return $media instanceof Media ? URL::temporarySignedRoute('prompts.export', now()->addHours(2), [
            'prompt' => $this->prompt->id,
            'media' => $media->id,
            'owner' => $this->channel->owner_id,
        ]) : '';
    }

    protected function getSourceId(): int
    {
        return $this->prompt instanceof PublishVideoData ? ($this->prompt->seriesAssemblyId ?? $this->prompt->episodeAssemblyId ?? $this->prompt->short->id ?? throw new RuntimeException('The publication has no source.')) : $this->prompt->id;
    }

    protected function assertProjectActive(): void
    {
        if (! $this->projectActive->run($this->channel, $this->prompt)) {
            throw new RuntimeException('The project is disabled.');
        }
    }

    protected function getUrl(string $id): string
    {
        if ($this->prompt instanceof PublishVideoData && $this->prompt->seriesAssemblyId !== null && $this->channel->type === ChannelType::YOUTUBE) {
            return 'https://www.youtube.com/watch?v=' . $id;
        }

        return sprintf($this->getUrlTemplate(), $id);
    }

    public function getUrlTemplate(): string
    {
        return '';
    }

    protected function savePost(?string $externalId, ?string $url, ?Carbon $publishedAt = null): void
    {
        $this->savePost->run(
            new PostData(
                $this->channel,
                $this->prompt instanceof Prompt ? $this->prompt : $this->prompt->short,
                $this->getTitle(),
                $this->getDescription(),
                $url,
                $externalId,
                $this->prompt instanceof PublishVideoData ? $this->prompt->episodeAssemblyId : null,
                $this->prompt instanceof PublishVideoData ? $this->prompt->publicationRequestId : null,
                $this->prompt instanceof PublishVideoData ? $this->prompt->seriesAssemblyId : null,
                $publishedAt,
            ),
        );
    }

    protected function getTitle(): string
    {
        return $this->prompt instanceof PublishVideoData ? $this->prompt->title : 'What if the animal ends up in another country #Shorts #AIArt #WhatIf';
    }

    protected function getDescription(): string
    {
        return $this->prompt instanceof PublishVideoData ? $this->prompt->description : 'Generated by AI';
    }
}
