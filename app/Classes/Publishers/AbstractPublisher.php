<?php

namespace App\Classes\Publishers;

use App\Data\PostData;
use App\Models\Channel;
use App\Models\Prompt;
use App\Tasks\SavePost;

abstract class AbstractPublisher implements Publisher
{
    public function __construct(
        protected readonly Channel $channel,
        protected readonly Prompt $prompt,
    ) {
    }

    protected function getDescription(): string
    {
        return 'Generated by Midjourney Shorts AI';
    }

    protected function getTitle(): string
    {
        return $this->prompt->prompt;
    }

    protected function getPath(): ?string
    {
        return $this->prompt->getFirstMedia()?->getPath();
    }

    protected function savePost(string $externalId): void
    {
        app(SavePost::class)->run(
            $this->channel,
            new PostData(
                $this->getTitle(),
                $this->getDescription(),
                $externalId,
            ),
        );
    }
}
